// Helper maps
const nodeMap = new Map<string, GraphNodeDefinition>(
  DEMO_NODES.map((n) => [n.id, n])
);
const edgeMap = new Map<string, GraphEdgeDefinition>(
  DEMO_EDGES.map((e) => [e.id, e])
);

export function getNodeById(id: string): GraphNodeDefinition | undefined {
  return nodeMap.get(id);
}

export function getEdgeById(id: string): GraphEdgeDefinition | undefined {
  return edgeMap.get(id);
}

export function findEdgeBetween(
  fromNodeId: string,
  toNodeId: string
): GraphEdgeDefinition | undefined {
  return DEMO_EDGES.find(
    (e) =>
      (e.from_node_id === fromNodeId && e.to_node_id === toNodeId) ||
      (e.bidirectional &&
        e.from_node_id === toNodeId &&
        e.to_node_id === fromNodeId)
  );
}
